"""Generate lossless Rust coefficient tables from pinned ERFA 2.0.1 sources.

No network access or Python astronomy dependency is required. Place the three
unmodified sources in --source-dir from https://github.com/liberfa/erfa/tree/v2.0.1.
The source hashes and expected term counts prevent accidental model changes.
ERFA's full BSD notice is retained in the generated source.
"""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
HASHES = {
    "nut00b.c": "a5246d525e987eb587bbe786b2846160e01be85b5d12af573870b89235695f49",
    "s06.c": "6ad19dd59c3150d9f065b3f76d254c1cf3adb0cb6bacd6422c1dc6b6f14122ea",
    "LICENSE": "b1858f9a263f22c438a455a32945da51a31a0ae25a21055da13bb7ed57cc3b51",
}


def verified_text(source_dir: Path, name: str) -> str:
    data = (source_dir / name).read_bytes()
    if hashlib.sha256(data).hexdigest() != HASHES[name]:
        raise ValueError(f"{name} differs from the pinned ERFA 2.0.1 source")
    return data.decode("utf-8")


def values(text: str) -> list[str]:
    fields = [field.strip() for field in text.split(",") if field.strip()]
    if not all(re.fullmatch(r"[+-]?\d+(?:\.\d*)?(?:[eE][+-]?\d+)?", v) for v in fields):
        raise ValueError("Unexpected coefficient syntax")
    return fields


def float_literal(value: str) -> str:
    return value if "." in value or "e" in value.lower() else value + ".0"


def generate(source_dir: Path) -> str:
    nutation = verified_text(source_dir, "nut00b.c")
    cio = verified_text(source_dir, "s06.c")
    license_text = verified_text(source_dir, "LICENSE")
    output = [
        "// Generated by scripts/prepare_orientation.py; do not edit coefficients.",
        "// ERFA 2.0.1, https://github.com/liberfa/erfa/tree/v2.0.1",
        "// Derived from SOFA via ERFA; this is not the unmodified SOFA standard.",
        "// Source SHA256:",
        *[f"// {name}: {digest}" for name, digest in HASHES.items()],
        "//",
        *["// " + line if line else "//" for line in license_text.splitlines()],
        "",
    ]
    block = re.search(r"\}\s*x\[\]\s*=\s*\{(.*?)\n\s*\};", nutation, re.S)
    if block is None:
        raise ValueError("Nutation table not found")
    terms = re.findall(r"\{([^{}]+)\}", re.sub(r"/\*.*?\*/", "", block.group(1), flags=re.S))
    if len(terms) != 77:
        raise ValueError("Expected exactly 77 IAU 2000B nutation terms")
    output += ["#[rustfmt::skip]", "const NUTATION_TERMS: [NutationTerm; 77] = ["]
    for term in terms:
        parts = values(term)
        if len(parts) != 11:
            raise ValueError("Malformed nutation term")
        args = ", ".join(str(int(v)) for v in parts[:5])
        coeff = ", ".join(float_literal(v) for v in parts[5:])
        output.append(f"    NutationTerm {{ arguments: [{args}], coefficients: [{coeff}] }},")
    output += ["];", ""]
    for order, count in enumerate([33, 3, 25, 4, 1]):
        block = re.search(rf"static const TERM s{order}\[\]\s*=\s*\{{(.*?)\n\s*\}};", cio, re.S)
        if block is None:
            raise ValueError(f"CIO s{order} table not found")
        terms = re.findall(r"\{\{([^{}]+)\},([^{}]+)\}", block.group(1))
        if len(terms) != count:
            raise ValueError(f"Wrong CIO s{order} term count")
        output += ["#[rustfmt::skip]", f"const CIO_ORDER_{order}: [CioTerm; {count}] = ["]
        for argument_text, coefficient_text in terms:
            args = values(argument_text)
            coeff = values(coefficient_text)
            if len(args) != 8 or len(coeff) != 2:
                raise ValueError("Malformed CIO term")
            output.append(
                "    CioTerm { arguments: [" + ", ".join(str(int(v)) for v in args)
                + "], sin: " + float_literal(coeff[0])
                + ", cos: " + float_literal(coeff[1]) + " },"
            )
        output += ["];", ""]
    return "\n".join(output)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-dir", type=Path, default=ROOT / ".cache/astronomy/erfa")
    parser.add_argument("--output", type=Path, default=ROOT / "crates/earth-math/src/astro/orientation_coefficients.rs")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = generate(args.source_dir)
    if args.check:
        if args.output.read_text(encoding="utf-8") != expected:
            raise SystemExit("Generated orientation coefficients differ; regenerate")
        print("Pinned ERFA orientation coefficient tables verified")
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(expected, encoding="utf-8", newline="\n")
        print(f"Wrote 77 nutation and 66 CIO terms to {args.output}")


if __name__ == "__main__":
    main()
