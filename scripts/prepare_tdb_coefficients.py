"""Extract the geocentric Fairhead TDB−TT series from pinned ERFA2.0.1.

Input: .cache/astronomy/erfa/dtdb.c and LICENSE, fetched unchanged from
https://github.com/liberfa/erfa/tree/v2.0.1 . No coefficient rounding occurs.
"""
from pathlib import Path
import hashlib
import re
import argparse

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / ".cache/astronomy/erfa/dtdb.c"
OUTPUT = ROOT / "crates/earth-math/src/astro/tdb_coefficients.rs"


def generate() -> str:
    source = SOURCE.read_text()
    table = source.split("fairhd[787][3] = {", 1)[1].split("};", 1)[0]
    table = re.sub(r"/\*.*?\*/", "", table, flags=re.S)
    rows = re.findall(r"\{\s*([^{}]+)\s*\}", table)
    if len(rows) != 787:
        raise ValueError("Expected the complete 787-term Fairhead series")
    license_text = (SOURCE.parent / "LICENSE").read_text()
    output = "// Generated by scripts/prepare_tdb_coefficients.py; ERFA2.0.1.\n"
    output += "// Source SHA256: " + hashlib.sha256(SOURCE.read_bytes()).hexdigest() + "\n"
    output += "/*\n" + license_text + "\n*/\n"
    output += "#[rustfmt::skip]\nstatic FAIRHEAD: [[f64; 3]; 787] = [\n"
    for row in rows:
        values = [part.strip() for part in row.split(",")]
        if len(values) != 3:
            raise ValueError("Malformed coefficient")
        for value in values:
            float(value)
        output += "    [" + ", ".join(values) + "],\n"
    return output + "];\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = generate()
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != text:
            raise SystemExit("TDB coefficient file differs from pinned source")
    else:
        OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print("Verified 787 unchanged ERFA Fairhead coefficients")
