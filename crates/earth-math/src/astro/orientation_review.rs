// Independently generated with Python ERFA; see scripts/verify_astronomy_orientation.py.
use super::{Vec3d, orientation::earth_orientation};
#[test]
fn orientation_matches_independent_erfa_reference_and_preserves_geometry() {
    #[rustfmt::skip]
    let cases = [
(0.0,-64.184,0.0,0.0,4.890280841637995,[[0.17695510840794312, -0.9842189233543193, -2.279468097702032e-05], [0.9842189232494262, 0.1769551076600922, 3.147610106743808e-05], [-2.6945739077619553e-05, -2.8004813243664998e-05, 0.9999999992448287]]),
(-4733640000.25,-4733640007.25,1.2e-06,-2.1e-06,1.7662224791374825,[[-0.19416688138513433, 0.9809651906491287, -0.002552823513172346], [-0.9808600025994761, -0.19418345198929432, -0.014368099181054809], [-0.014590321234516269, -0.0002858465316514841, 0.9998935147394616]]),
(-3155760000.125,-3155760002.125,-8e-07,4e-07,4.90372798757366,[[0.19016552104360684, -0.9817505294216617, 0.0017241190506361375], [0.9817042851776152, 0.190173299048504, 0.009529574645048573], [-0.009683546360751527, -0.00011962146753374886, 0.9999531062107782]]),
(845856123.456,845856054.333,7e-07,1.7e-06,3.662257985531248,[[-0.8674853803190055, -0.4974574103644735, 0.0022890623107067144], [0.49745576915175854, -0.8674883999106046, -0.001278185499675325], [0.002621577849844546, 2.990001810482296e-05, 0.9999965632118772]]),
(3155760000.75,3155759798.75,-4e-07,-1.3e-06,4.871364098928559,[[0.15829853024553214, -0.9873899923634493, -0.0016057093796167671], [0.9873434594384998, 0.1583066592687264, -0.009586174168612306], [0.009719486926784388, -6.790937215465183e-05, 0.9999527623654015]]),
(4733640000.5,4733639700.5,0.0,0.0,1.7181460761032312,[[-0.1467990720804882, 0.9891634500998289, 0.0023877652545180846], [-0.989059530874675, -0.14681826584879595, 0.014340195226012448], [0.014535364538789926, -0.0002565146298408316, 0.9998943231051816]])
];

    for (tt, ut1, xp, yp, expected_era, expected_matrix) in cases {
        let (matrix, era) = earth_orientation(tt, ut1, xp, yp);
        assert!(
            (era - expected_era).abs() < 2e-12,
            "ERA {tt}: {era} vs {expected_era}"
        );
        for (row, expected) in matrix.rows.iter().zip(expected_matrix) {
            for (actual, reference) in row.iter().zip(expected) {
                assert!(
                    (actual - reference).abs() < 2e-12,
                    "matrix {tt}: {actual} vs {reference}"
                );
            }
        }
        let vector = Vec3d::new(6378137.0, -1234567.0, 4567890.0);
        let rotated = matrix.transform(vector);
        let recovered = matrix.transpose().transform(rotated);
        assert!((vector - recovered).length() < 1e-8);
        let x = matrix.transform(Vec3d::new(1.0, 0.0, 0.0));
        let y = matrix.transform(Vec3d::new(0.0, 1.0, 0.0));
        let z = matrix.transform(Vec3d::new(0.0, 0.0, 1.0));
        assert!((x.cross(y) - z).length() < 1e-14);
    }
}
